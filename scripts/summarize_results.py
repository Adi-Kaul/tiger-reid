"""results/results.csv -> results/summary.md (one row per method, test split).

    python scripts/summarize_results.py
Seeds of the same method are averaged (± std). CIs come from the first seed's
bootstrap. Val rows are for choosing settings and are left out.
"""

import pandas as pd

from tiger_reid.data import REPO
from tiger_reid.results import RESULTS_CSV

OUT = REPO / "results" / "summary.md"


def fmt(series, pct=True):
    scale = 100 if pct else 1
    m, s = series.mean() * scale, series.std() * scale
    d = 1 if pct else 2
    return f"{m:.{d}f}" if len(series) < 2 or pd.isna(s) else f"{m:.{d}f} ± {s:.{d}f}"


def summarize(df: pd.DataFrame) -> pd.DataFrame:
    test = df[df.eval_split == "test"]
    rows = []
    for method, g in test.groupby("method", sort=False):
        first = g.iloc[0]
        rows.append({
            "method": method,
            "seeds": len(g),
            "rank-1 %": fmt(g.rank1),
            "rank-1 95% CI": f"[{first.rank1_lo * 100:.0f}, {first.rank1_hi * 100:.0f}]",
            "rank-5 %": fmt(g.rank5),
            "mAP %": fmt(g.mAP),
            "AUROC": fmt(g.auroc, pct=False),
            "AUROC 95% CI": f"[{first.auroc_lo:.2f}, {first.auroc_hi:.2f}]",
            "AUROC (all unknowns)": fmt(g.auroc_all, pct=False),
        })
    return pd.DataFrame(rows)


OPS = [("fy5", "5% false-yes target"), ("fy10", "10% false-yes target"), ("keep95", "keep 95% of knowns")]


def operating_points(df: pd.DataFrame) -> pd.DataFrame:
    """D26: per threshold (fit on each seed's val), test false yes / knowns auto-recognized."""
    if "fy_fy5" not in df.columns:
        return pd.DataFrame()
    test = df[(df.eval_split == "test") & df["fy_fy5"].notna()]
    rows = []
    for method, g in test.groupby("method", sort=False):
        for key, label in OPS:
            rows.append({
                "method": method, "threshold (set on val)": label, "seeds": len(g),
                "false yes, unknowns %": fmt(g[f"fy_{key}"]),
                "false yes, all unknowns %": fmt(g[f"fy_all_{key}"]),
                "knowns recognized automatically %": fmt(g[f"known_auto_{key}"]),
                "rank-1 among those %": fmt(g[f"rank1_auto_{key}"]),
                "sent to review (knowns) %": fmt(1 - g[f"known_auto_{key}"]),
            })
    return pd.DataFrame(rows)


def main():
    df = pd.read_csv(RESULTS_CSV)
    table = summarize(df)
    ops = operating_points(df)
    md = ("# Results (test split, splits v1)\n\n"
          "Generated by `scripts/summarize_results.py` from `results.csv`. "
          "Gallery = train images; 91 known queries; 19 matched unknowns (AUROC), "
          "129 for 'all unknowns'. See docs/decisions.md D9–D10.\n\n"
          + table.to_markdown(index=False) + "\n")
    if len(ops):
        md += ("\n## Open-set operating points (D26)\n\n"
               "Thresholds are fit on each seed's val (z-scores too) and applied once to test. "
               "Photos at or below the threshold are recognized automatically; the rest go to human review. "
               "'false yes' = new tigers accepted as known (19 matched unknowns; 'all unknowns' = 129).\n\n"
               + ops.to_markdown(index=False) + "\n")
    OUT.write_text(md)
    print(md)


if __name__ == "__main__":
    main()
